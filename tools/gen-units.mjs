// Generates src/units-data.ts from spec/units.md (the normative unit list of SPEC.md 7.1).
//
//   node tools/gen-units.mjs            write src/units-data.ts
//   node tools/gen-units.mjs --check    exit 1 if src/units-data.ts differs from units.md
//
// units.md marks its machine-readable list as fenced blocks tagged `units-<group>` (currency,
// physical, ratio). Each block is whitespace-separated unit strings; a group may have several
// blocks (the currency list has two: ISO 4217 List One and withdrawn codes). Index units
// (`index:<period>=<value>`, units.md 2.4) are a pattern, not a list, and live in src/units.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const UNITS_MD = join(root, 'spec', 'units.md');
export const OUT = join(root, 'src', 'units-data.ts');

/** Parse the `units-…` fenced blocks of units.md into {group: [unit, ...]} in file order. */
export function parseUnitsMd(text) {
  const groups = {};
  const re = /^```units-([a-z]+)[ \t]*\n([\s\S]*?)^```[ \t]*$/gm;
  let m;
  while ((m = re.exec(text))) {
    const tokens = m[2].split(/\s+/).filter(Boolean);
    (groups[m[1]] ??= []).push(...tokens);
  }
  const all = Object.values(groups).flat();
  if (new Set(all).size !== all.length) throw new Error('units.md lists a unit twice');
  for (const g of ['currency', 'physical', 'ratio']) if (!groups[g]?.length) throw new Error(`units.md has no units-${g} block`);
  for (const c of groups.currency) if (!/^[A-Z]{3}$/.test(c)) throw new Error(`not a currency code: ${c}`);
  for (const u of all) if (!/^[!-~]+$/.test(u)) throw new Error(`unit is not printable ASCII: ${JSON.stringify(u)}`);
  return groups;
}

/** The text of src/units-data.ts for a units.md text. */
export function render(text) {
  const groups = parseUnitsMd(text);
  const line = (xs) => xs.map((x) => JSON.stringify(x)).join(', ');
  const body = Object.keys(groups)
    .map((g) => `  ${g}: [${line(groups[g])}],`)
    .join('\n');
  return `// GENERATED by tools/gen-units.mjs from spec/units.md (the \`units-…\` fenced blocks).
// Do not edit by hand; test/units.test.mjs checks that this file matches units.md.

/** Literal units by group, in units.md order. Index units (units.md 2.4) are a pattern. */
export const UNIT_GROUPS: { readonly [group: string]: readonly string[] } = {
${body}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = render(readFileSync(UNITS_MD, 'utf8'));
  if (process.argv[2] === '--check') {
    const have = readFileSync(OUT, 'utf8');
    if (have !== want) {
      console.error('src/units-data.ts differs from spec/units.md; run node tools/gen-units.mjs');
      process.exit(1);
    }
    console.log('src/units-data.ts matches spec/units.md');
  } else {
    writeFileSync(OUT, want);
    const g = parseUnitsMd(readFileSync(UNITS_MD, 'utf8'));
    console.log(Object.entries(g).map(([k, v]) => `${k} ${v.length}`).join(', '));
  }
}
