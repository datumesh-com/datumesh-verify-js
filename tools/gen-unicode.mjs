// Generates src/unicode-data.ts from the Unicode 15.1.0 Character Database.
//
//   node tools/gen-unicode.mjs <dir with UnicodeData.txt and DerivedNormalizationProps.txt>
//
// Sources (download from https://www.unicode.org/Public/15.1.0/ucd/):
//   UnicodeData.txt               general category, canonical combining class, decompositions
//   DerivedNormalizationProps.txt Full_Composition_Exclusion
// plus spec/tools/unicode-15.1-assigned.txt (SPEC.md 3.5), which is cross-checked against
// UnicodeData.txt: the generator fails if the two disagree.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ucd = process.argv[2];
if (!ucd) throw new Error('usage: node tools/gen-unicode.mjs <ucd-dir>');

const unicodeData = readFileSync(join(ucd, 'UnicodeData.txt'), 'utf8');
const header = unicodeData.slice(0, 0); // UnicodeData.txt has no version header; checked below
void header;
const dnp = readFileSync(join(ucd, 'DerivedNormalizationProps.txt'), 'utf8');
if (!dnp.startsWith('# DerivedNormalizationProps-15.1.0.txt')) throw new Error('DerivedNormalizationProps is not 15.1.0');

const gc = new Map();
const ccc = new Map();
const decomp = new Map(); // single-level canonical decompositions
let rangeStart = null;
for (const line of unicodeData.split('\n')) {
  if (!line) continue;
  const f = line.split(';');
  const cp = parseInt(f[0], 16);
  if (f[1].endsWith(', First>')) { rangeStart = cp; continue; }
  const lo = f[1].endsWith(', Last>') ? rangeStart : cp;
  for (let c = lo; c <= cp; c++) {
    gc.set(c, f[2]);
    if (+f[3]) ccc.set(c, +f[3]);
  }
  if (f[5] && !f[5].startsWith('<')) decomp.set(cp, f[5].split(' ').map((h) => parseInt(h, 16)));
}
// Unicode 15.1 added U+2FFC..U+2FFF and U+31EF; 16.0 added U+1C89. Sanity-check the file version.
if (!gc.has(0x31ef) || gc.has(0x1c89)) throw new Error('UnicodeData.txt is not 15.1.0');

// Assigned ranges from the spec's data file, cross-checked against UnicodeData.txt.
const assignedTxt = readFileSync(join(root, 'spec/tools/unicode-15.1-assigned.txt'), 'utf8');
const assigned = [];
for (const line of assignedTxt.split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [a, b] = line.trim().split('..').map((h) => parseInt(h, 16));
  assigned.push(a, b);
}
const inSpec = new Uint8Array(0x110000);
for (let i = 0; i < assigned.length; i += 2) for (let c = assigned[i]; c <= assigned[i + 1]; c++) inSpec[c] = 1;
for (let c = 0; c < 0x110000; c++) {
  const ucdAssigned = gc.has(c) && gc.get(c) !== 'Cn';
  if (!!inSpec[c] !== ucdAssigned) throw new Error(`assigned mismatch at U+${c.toString(16)}`);
}

const fce = new Set();
for (const line of dnp.split('\n')) {
  const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*Full_Composition_Exclusion\b/.exec(line);
  if (!m) continue;
  const a = parseInt(m[1], 16), b = m[2] ? parseInt(m[2], 16) : a;
  for (let c = a; c <= b; c++) fce.add(c);
}

// Full canonical decompositions (recursively expanded); Hangul syllables are algorithmic.
const full = (cp) => (decomp.has(cp) ? decomp.get(cp).flatMap(full) : [cp]);
const hex = (n) => n.toString(16);
const decompEntries = [...decomp.keys()].sort((a, b) => a - b).map((cp) => `${hex(cp)}:${full(cp).map(hex).join('.')}`);
// Primary composites: canonical decompositions of exactly two code points, not excluded.
const compEntries = [...decomp.entries()]
  .filter(([cp, d]) => d.length === 2 && !fce.has(cp))
  .sort((a, b) => a[0] - b[0])
  .map(([cp, d]) => `${hex(d[0])}.${hex(d[1])}:${hex(cp)}`);
// Combining classes as runs: start:end:class
const cccRuns = [];
const cps = [...ccc.keys()].sort((a, b) => a - b);
for (let i = 0; i < cps.length; ) {
  let j = i;
  while (j + 1 < cps.length && cps[j + 1] === cps[j] + 1 && ccc.get(cps[j + 1]) === ccc.get(cps[i])) j++;
  cccRuns.push(`${hex(cps[i])}:${hex(cps[j])}:${ccc.get(cps[i])}`);
  i = j + 1;
}

const out = `// GENERATED by tools/gen-unicode.mjs from the Unicode 15.1.0 Character Database
// (UnicodeData.txt, DerivedNormalizationProps.txt) and spec/tools/unicode-15.1-assigned.txt.
// Do not edit by hand.

/** Assigned code point ranges (General_Category != Cn), inclusive pairs, ascending. */
export const ASSIGNED: readonly number[] = [${assigned.join(',')}];

/** Non-zero canonical combining classes: "start:end:class" in hex/hex/decimal, ';'-separated. */
export const CCC = '${cccRuns.join(';')}';

/** Full canonical decompositions (non-Hangul): "cp:cp.cp..." in hex, ';'-separated. */
export const DECOMP = '${decompEntries.join(';')}';

/** Primary composites: "first.second:composite" in hex, ';'-separated. */
export const COMP = '${compEntries.join(';')}';
`;
writeFileSync(join(root, 'src/unicode-data.ts'), out);
console.log(`assigned ranges ${assigned.length / 2}, ccc runs ${cccRuns.length}, decompositions ${decompEntries.length}, compositions ${compEntries.length}`);
